import numpy as np


def subtract_dark(y, n_points=50, clip_zero=False):
    """Вычитает средний уровень темнового тока/фона по первым n_points точкам."""
    y = np.asarray(y, dtype=float)
    if y.size == 0:
        raise ValueError("Массив спектра y пуст.")
    n_pts = min(int(n_points), y.size)
    y_corr = y - np.mean(y[:n_pts])
    if clip_zero:
        y_corr = np.clip(y_corr, 0.0, None)
    return y_corr


def integrate_spectrum(x, y, peak_range=None):
    """Интегрирует спектр (опционально в окне peak_range=(x_min, x_max)) через np.trapezoid."""
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)

    order = np.argsort(x)
    x, y = x[order], y[order]

    if peak_range is not None:
        lo, hi = min(peak_range), max(peak_range)
        mask = (x >= lo) & (x <= hi)
        x, y = x[mask], y[mask]

    if x.size < 2:
        return np.nan
    return float(np.trapezoid(y, x))


def fit_segment_coeffs(x, y, segment):
    """
    Линейный фит в log-log координатах на отрезке segment=(x_min, x_max).
    Возвращает (n, b), где log10(y) = n * log10(x) + b.
    """
    x_min, x_max = segment
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)

    mask = np.isfinite(x) & np.isfinite(y) & (x > 0) & (y > 0)
    if x_min is not None:
        mask &= x >= x_min
    if x_max is not None:
        mask &= x <= x_max

    if np.count_nonzero(mask) < 2:
        raise ValueError(f"Недостаточно положительных точек для фита в сегменте {segment}")

    log_x = np.log10(x[mask])
    log_y = np.log10(y[mask])
    n, b = np.polyfit(log_x, log_y, deg=1)
    return float(n), float(b)



